"""The same-policy cost simulator: what a forecast would have cost under the operator's own v2 decision rule.

Trust promotes a challenger (E1-product) over seasonal-naive only when its same-policy shortage AND replica-time are
within challengerCostRatioBps of seasonal-naive's (design C2, section 7; evaluation manifest C2.8, prerequisite 2). Both
are measured by replaying the OPERATOR'S policy, not an approximation of it:

  replay() is a line-for-line port of replayV2 (k8s-operator/controllers/replay_v2_test.go), which runs the very
  functions Reconcile uses (v2PredictiveReplicas, unifiedDesired, headroomFloor/headroomEventual,
  calculateScaleDownTarget, the fresh-Active restart hold) on recorded step times; TestV2ReplayMatchesReconcile and
  TestV2TimedReplayMatchesReconcile prove Reconcile decides the same. testdata/v2-policy-parity.json (generated by Go)
  holds this port to replayV2 decision for decision (tests/test_policy_sim.py); a policy change that is not mirrored
  here fails both test suites.

paired_costs() replays the challenger and the baseline over the same decisions of one retained paired window: the same
controller inputs, bounds, capacity, caps, headroom and startup delay; at a decision where either forecast has no
issued bound, both are reactive, so the costs differ only where both forecasts existed. The controller's measured rate
at a decision is what was AVAILABLE then (controller_rps: the newest observation the forecaster had received for that
decision), never the later truth; the eventual measurement (truth_rps) only scores. From each replay:
  replica_time = integral of the replicas the policy requested (provisioned cost, ready or not), replica-seconds;
  shortage     = integral of max(n*(t) - ready(t), 0), replica-seconds, with n*(t) = measured RPS / capacity
                 (fractional, unclipped) and ready(t) the replicas that have finished starting: each scale-up starts a
                 cohort that becomes ready D (the startup delay) later; a scale-down removes starting replicas first
                 (newest first), then ready ones, as a ReplicaSet deletes unready pods first. So a scale-down followed
                 by a scale-up within D does not resurrect ready capacity. Time without a measurement is excluded and
                 reported (unknown truth is not zero shortage).
The result carries its binding (epoch, both models and recipes, the window, and the fingerprint of the policy:
capacity, bounds, caps, headroom, startup delay, decision interval); trust uses it only when every part matches.
These are capacity proxies for comparing two forecasts under one policy, not service latency.
"""

from __future__ import annotations

import math
from dataclasses import asdict, dataclass
from typing import Dict, List, Mapping, Optional, Sequence, Tuple

from forecasting.contracts import canonical_json, sha256_hex

POLICY_SCHEMA = "v2-policy/1"
COSTS_SCHEMA = "policy-costs/v1"
SCALE_DOWN_STABILIZATION_S = 300        # Go scaleDownStabilization
SCALE_DOWN_COOLDOWN_S = 120             # Go scaleDownCooldown
SCALE_DOWN_MAX_PERCENT = 10             # Go scaleDownMaxPercent
SCALE_DOWN_MIN_PODS = 2                 # Go scaleDownMinPods
INT32_MAX = 2 ** 31 - 1


@dataclass(frozen=True)
class PolicyParams:
    min_replicas: int
    max_replicas: int
    capacity_rpm: float
    headroom_percent: int
    max_extra_replicas: int
    max_extra_percent: int
    startup_delay_seconds: int = 0
    decision_interval_seconds: int = 60

    def fingerprint(self) -> str:
        return sha256_hex(canonical_json({"schema": POLICY_SCHEMA, **asdict(self)}))


@dataclass(frozen=True)
class Step:
    t: int                       # epoch seconds
    rpm: Optional[float]         # None: the rate could not be measured (hold)
    upper_rps: Optional[float]   # None: no forecast used (reactive only)


@dataclass(frozen=True)
class Decision:
    t: int
    current: int
    reactive: int
    predictive: Optional[int]
    cap_binding: bool
    desired: int
    applied: int


def bounded_replicas(x: float) -> int:
    """Go boundedReplicas: NaN and non-positive -> 0, saturating at int32, truncating otherwise."""
    if math.isnan(x) or x <= 0:
        return 0
    if x >= INT32_MAX:
        return INT32_MAX
    return int(x)


def predictive_replicas(upper_rps: float, capacity_rpm: float, reactive: int, min_replicas: int, max_extra: int,
                        max_percent: int) -> Tuple[int, bool]:
    """Go v2PredictiveReplicas: (capped predictive replicas, cap binding)."""
    uncapped = bounded_replicas(math.ceil(upper_rps * 60 / capacity_rpm))
    base = max(reactive, min_replicas)
    by_percent = (max_percent * base + 99) // 100
    allowance = min(max_extra, by_percent, INT32_MAX)
    limit = reactive + allowance
    return (limit, True) if uncapped > limit else (uncapped, False)


def unified_desired(predicted: int, reactive: int, min_replicas: int, max_replicas: int, current: int,
                    forecast_used: bool, telemetry_ok: bool) -> int:
    """Go unifiedDesired."""
    def clamp(v):
        return max(min_replicas, min(max_replicas, v))
    if not telemetry_ok:
        return clamp(current)
    desired = predicted if forecast_used else 0
    return clamp(max(desired, reactive))


def headroom_floor(rpm: float, per_pod_rpm: float, headroom_percent: int, max_replicas: int) -> int:
    """Go headroomFloor."""
    if headroom_percent <= 0 or headroom_percent >= 100 or not per_pod_rpm > 0 or math.isnan(rpm) or \
            math.isinf(rpm) or rpm < 0:
        return 0
    return min(bounded_replicas(math.ceil(rpm / (per_pod_rpm * (1 - headroom_percent / 100)))), max_replicas)


class _State:
    def __init__(self, now: int):
        self.last_up, self.last_down, self.below_since = now, now, None    # a fresh Active state


def _scale_down_target(state: _State, now: int, current: int, desired: int) -> int:
    """Go calculateScaleDownTarget (the overestimate override is never active on the v2 path)."""
    if state.last_up is not None and now - state.last_up < SCALE_DOWN_STABILIZATION_S:
        return current
    if state.below_since is None:
        state.below_since = now
        return current
    if now - state.below_since < SCALE_DOWN_STABILIZATION_S:
        return current
    if state.last_down is not None and now - state.last_down < SCALE_DOWN_COOLDOWN_S:
        return current
    max_remove = max(int(math.ceil(current * SCALE_DOWN_MAX_PERCENT / 100.0)), SCALE_DOWN_MIN_PODS)
    return max(current - max_remove, desired, 1)


def replay(params: PolicyParams, steps: Sequence[Step], current: int) -> List[Decision]:
    """replayV2, step for step, on the steps' own times, from a fresh Active state at `current`."""
    p = params
    out: List[Decision] = []
    if not steps:
        return out
    state = _State(steps[0].t)
    for s in steps:
        now = s.t
        measured = s.rpm is not None
        reactive = bounded_replicas(math.ceil(s.rpm / p.capacity_rpm)) if measured else 0
        predicted, used, binding, predictive = 0, False, False, None
        if s.upper_rps is not None:
            predicted, binding = predictive_replicas(s.upper_rps, p.capacity_rpm, reactive, p.min_replicas,
                                                     p.max_extra_replicas, p.max_extra_percent)
            used, predictive = True, predicted
        desired = unified_desired(predicted, reactive, p.min_replicas, p.max_replicas, current, used, measured)
        applied = current
        if desired > current:
            applied = desired
            state.last_up, state.below_since = now, None
        elif desired < current:
            floor = headroom_floor(s.rpm, p.capacity_rpm, p.headroom_percent, p.max_replicas) if measured else 0
            eventual = max(desired, floor)
            if eventual >= current:                       # Go headroomEventual: the floor holds it
                state.below_since = None
            else:
                applied = _scale_down_target(state, now, current, eventual)
            if applied < current:
                state.last_down = now
        else:
            state.below_since = None
        out.append(Decision(now, current, reactive, predictive, binding, desired, applied))
        current = applied
    return out


# --- the policy of a live autoscaler ------------------------------------------------------------------------------

DEFAULT_HEADROOM_PERCENT = 10            # Go DefaultScaleDownHeadroomPercent
DEFAULT_RECONCILE_S, MIN_RECONCILE_S = 60, 30
MAX_CAPACITY_RPS = 1e6
_QUANTITY_SUFFIX = {"m": 1e-3, "k": 1e3, "M": 1e6, "G": 1e9, "Ki": 1024.0, "Mi": 1024.0 ** 2, "Gi": 1024.0 ** 3}


def quantity(value) -> Optional[float]:
    """A Kubernetes quantity (number, decimal or exponent string, or m/k/M/G/Ki/Mi/Gi suffix) as a float, else None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    if not isinstance(value, str) or not value:
        return None
    for suffix in sorted(_QUANTITY_SUFFIX, key=len, reverse=True):
        if value.endswith(suffix):
            try:
                return float(value[:-len(suffix)]) * _QUANTITY_SUFFIX[suffix]
            except ValueError:
                return None
    try:
        return float(value)
    except ValueError:
        return None


def capacity_rpm(spec: Mapping) -> Optional[float]:
    """Go perReplicaCapacityRPM: capacityPerReplica (requests/second) or the deprecated targetRPS, x 60; None when
    neither or both are set or the value is out of (0, 1e6] requests per second."""
    req = ((spec.get("metrics") or {}).get("requests") or {})
    target = req.get("targetRPS") or 0
    if req.get("capacityPerReplica") is not None:
        rps = quantity(req["capacityPerReplica"])
        if target or rps is None or math.isnan(rps) or not 0 < rps <= MAX_CAPACITY_RPS:
            return None
        return rps * 60
    if isinstance(target, int) and not isinstance(target, bool) and target > 0:
        return float(target) * 60
    return None


def decision_interval(spec: Mapping, interval: int) -> int:
    """Go v2DecisionInterval of the reconcile interval (spec.prediction.updateIntervalSeconds, default 60, at least 30)
    rounded up to the grid."""
    rec = (spec.get("prediction") or {}).get("updateIntervalSeconds") or DEFAULT_RECONCILE_S
    rec = max(int(rec), MIN_RECONCILE_S)             # = contracts.effective_update_interval (the bound settings' value)
    return max(-(-rec // interval) * interval, interval)


def resolve_policy(spec: Mapping, settings, lead) -> Tuple[Optional[PolicyParams], str]:
    """(the operator's v2 policy for this autoscaler, "") or (None, why): no capacity, no lead, bad bounds."""
    cap = capacity_rpm(spec)
    if cap is None:
        return None, "no per-replica capacity (spec.metrics.requests.capacityPerReplica)"
    if lead is None:
        return None, "no lead (startup delay) yet"
    lo, hi = spec.get("minReplicas"), spec.get("maxReplicas")
    if not all(isinstance(v, int) and not isinstance(v, bool) for v in (lo, hi)) or not 1 <= lo <= hi:
        return None, "malformed replica bounds"
    scale_down = ((spec.get("behavior") or {}).get("scaleDown") or {})
    headroom = scale_down.get("headroomPercent")
    headroom = DEFAULT_HEADROOM_PERCENT if headroom is None else headroom
    if not isinstance(headroom, int) or isinstance(headroom, bool) or not 0 <= headroom <= 99:
        return None, "malformed spec.behavior.scaleDown.headroomPercent"
    return PolicyParams(min_replicas=lo, max_replicas=hi, capacity_rpm=cap, headroom_percent=headroom,
                        max_extra_replicas=settings.predictive_extra.max_replicas,
                        max_extra_percent=settings.predictive_extra.max_percent,
                        startup_delay_seconds=lead.startup_delay_seconds,
                        decision_interval_seconds=decision_interval(spec, settings.sample_interval_seconds)), ""


# --- costs ------------------------------------------------------------------------------------------------------

class _Pods:
    """Replicas by state: `ready`, plus starting cohorts [ready_at, n] in start order."""

    def __init__(self, ready: int):
        self.ready, self.starting = ready, []

    @property
    def total(self) -> int:
        return self.ready + sum(n for _, n in self.starting)

    def promote(self, now: float) -> None:
        while self.starting and self.starting[0][0] <= now:
            self.ready += self.starting.pop(0)[1]

    def scale(self, target: int, now: float, startup_delay: int) -> None:
        diff = target - self.total
        if diff > 0:
            self.starting.append([now + startup_delay, diff])
            self.promote(now)
        while diff < 0 and self.starting:                 # starting replicas go first, the newest cohort first
            take = min(-diff, self.starting[-1][1])
            self.starting[-1][1] -= take
            diff += take
            if self.starting[-1][1] == 0:
                self.starting.pop()
        if diff < 0:
            self.ready += diff


def window_costs(decisions: Sequence[Decision], initial: int, truth_rps: Mapping[int, float], interval: int,
                 capacity_rps: float, startup_delay: int, start: int, end: int) -> Dict[str, float]:
    """Exact piecewise integrals over [start, end): replica_time, shortage and the seconds without truth. `initial`
    replicas are ready at the start; decisions apply at their own times (module docstring for ready(t))."""
    points = {start, end}
    for d in decisions:
        for b in (d.t, d.t + startup_delay):
            if start < b < end:
                points.add(b)
    first_slot = start - start % interval
    for slot in range(first_slot, end + 1, interval):
        if start < slot < end:
            points.add(slot)
    cuts = sorted(points)
    pods, i = _Pods(initial), 0
    replica_time = shortage = unknown = 0.0
    for a, b in zip(cuts, cuts[1:]):
        while i < len(decisions) and decisions[i].t <= a:  # every change happens at a cut: constant on [a, b)
            pods.promote(decisions[i].t)
            pods.scale(decisions[i].applied, decisions[i].t, startup_delay)
            i += 1
        pods.promote(a)
        width = b - a
        replica_time += pods.total * width
        rps = truth_rps.get(int(a - a % interval))
        if rps is None:
            unknown += width
        else:
            shortage += max(rps / capacity_rps - pods.ready, 0.0) * width
    return {"replica_time": replica_time, "shortage": shortage, "unknown_truth_seconds": unknown,
            "seconds": float(end - start)}


def paired_costs(*, epoch: str, challenger: Tuple[str, str], baseline: Tuple[str, str], params: PolicyParams,
                 truth_rps: Mapping[int, float], challenger_upper: Mapping[int, float],
                 baseline_upper: Mapping[int, float], start: int, end: int, interval: int,
                 window_offset: int = 0, controller_rps: Optional[Mapping[int, float]] = None) -> Dict:
    """Same-policy costs of the challenger and the baseline over the decisions start, start + C, ..., end (C the
    decision interval), integrated over [start, end + C). (model, recipe) pairs name the two forecasts. The binding's
    window is in the coordinate trust's retained pairs use, the issued WINDOW ENDS: [start, end] + window_offset (the
    epoch's window end minus decision origin). controller_rps (default: truth_rps, for offline studies only) is the rate
    the controller had at each decision; truth_rps scores."""
    c = params.decision_interval_seconds
    inputs = truth_rps if controller_rps is None else controller_rps
    steps_c, steps_b, paired = [], [], 0
    for t in range(start, end + 1, c):
        rps = inputs.get(t)
        rpm = None if rps is None else rps * 60
        uc, ub = challenger_upper.get(t), baseline_upper.get(t)
        if uc is None or ub is None:
            uc = ub = None                                # matched: reactive for both where either is missing
        else:
            paired += 1
        steps_c.append(Step(t, rpm, uc))
        steps_b.append(Step(t, rpm, ub))
    cap_rps = params.capacity_rpm / 60
    out = {}
    for name, steps in (("challenger", steps_c), ("baseline", steps_b)):
        decisions = replay(params, steps, params.min_replicas)
        out[name] = window_costs(decisions, params.min_replicas, truth_rps, interval, cap_rps,
                                 params.startup_delay_seconds, start, end + c)
    return {"schema": COSTS_SCHEMA,
            "binding": {"epoch": epoch, "challenger": {"model": challenger[0], "recipe": challenger[1]},
                        "baseline": {"model": baseline[0], "recipe": baseline[1]},
                        "policy_sha256": params.fingerprint(),
                        "window": [start + window_offset, end + window_offset]},
            "shortage": [out["challenger"]["shortage"], out["baseline"]["shortage"]],
            "replica_time": [out["challenger"]["replica_time"], out["baseline"]["replica_time"]],
            "paired_decisions": paired, "decisions": len(steps_c),
            "unknown_truth_seconds": out["baseline"]["unknown_truth_seconds"], "seconds": out["baseline"]["seconds"]}
